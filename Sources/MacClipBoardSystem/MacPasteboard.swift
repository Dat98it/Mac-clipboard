import AppKit
import MacClipBoardCore

@MainActor public final class MacPasteboard: ClipboardAccess {
    private let pasteboard: NSPasteboard
    public init(_ pasteboard: NSPasteboard) { self.pasteboard = pasteboard }
    public var changeCount: Int { pasteboard.changeCount }

    public func capture(limits: HistoryLimits) -> CaptureResult {
        let before = changeCount
        guard let source = pasteboard.pasteboardItems, !source.isEmpty else { return .empty }
        guard source.count <= 128 else { return .tooLarge }
        // Password managers use these markers. Check types before requesting any payload bytes.
        let privateTypes: Set<String> = [
            "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        ]
        if source.contains(where: { !$0.types.map({ $0.rawValue }).filter(privateTypes.contains).isEmpty }) {
            return .privateContent
        }
        if source.allSatisfy({ $0.types.contains(.fileURL) }) {
            // Read files as NSURL objects so AppKit handles Finder file-reference URLs and
            // file-transfer access metadata. A raw string/data copy is not a native file transfer.
            guard let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
                  urls.count == source.count else {
                return before == changeCount ? .unsupported : .changedDuringRead
            }
            var items: [[ClipboardRepresentation]] = []
            var bytes = 0
            for url in urls {
                guard let pathURL = (url as NSURL).filePathURL, pathURL.isFileURL else { return .unsupported }
                let data = Data(pathURL.absoluteString.utf8)
                bytes += data.count
                guard bytes <= limits.maxEntryBytes else { return .tooLarge }
                // File-name text is a display fallback supplied by Finder, not a second content
                // item. Keep the transfer as files instead of offering editors plain text paths.
                items.append([ClipboardRepresentation(type: NSPasteboard.PasteboardType.fileURL.rawValue, data: data)])
            }
            guard before == changeCount else { return .changedDuringRead }
            // Finder attaches legacy and dynamic types to every file it copies. They are by-products of the file,
            // not content that was lost (restoring through NSURL recreates the native representations), so a
            // file reference never claims that "some formats were not saved".
            return .payload(ClipboardPayload(items: items, omittedTypeCount: 0))
        }
        var items: [[ClipboardRepresentation]] = []
        var bytes = 0, omitted = 0, lost = 0
        for sourceItem in source {
            var item: [ClipboardRepresentation] = []
            for type in sourceItem.types {
                guard ClipboardPayload.supportedTypes.contains(type.rawValue) else {
                    omitted += 1
                    if ClipboardPayload.lostContentTypes.contains(type.rawValue) { lost += 1 }
                    continue
                }
                guard let data = sourceItem.data(forType: type) else { return .unsupported }
                bytes += data.count
                guard bytes <= limits.maxEntryBytes else { return .tooLarge }
                item.append(ClipboardRepresentation(type: type.rawValue, data: data))
            }
            // Never drop an entire item from a multi-item copy, which could paste only some files.
            guard !item.isEmpty else { return .unsupported }
            items.append(item.sorted { $0.type < $1.type })
        }
        guard before == changeCount else { return .changedDuringRead }
        return .payload(ClipboardPayload(items: items, omittedTypeCount: omitted, lostContentCount: lost))
    }

    public func prepareRestore(_ payload: ClipboardPayload) async -> RestorePreparation {
        guard let urls = payload.fileURLs else { return .ready } // nil unless the payload is only file references
        let paths = urls.compactMap { ($0 as NSURL).filePathURL?.path }
        // Off the main actor: the first open() in a protected folder blocks until the user answers macOS's prompt.
        let denied = await Task.detached(priority: .userInitiated) { paths.contains { FileReadAccess.isDenied(path: $0) } }.value
        return denied ? .fileAccessDenied : .ready
    }

    public func restore(_ payload: ClipboardPayload) -> Bool {
        guard payload.isValid(limits: HistoryLimits()) else { return false }
        if payload.containsOnlyFileReferences {
            guard let urls = payload.fileURLs else { return false }
            var files: [NSURL] = []
            for url in urls {
                // Also migrate old history containing Finder's /.file/id=… reference URLs.
                guard let pathURL = (url as NSURL).filePathURL, pathURL.isFileURL,
                      (try? pathURL.checkResourceIsReachable()) == true else { return false }
                files.append(pathURL as NSURL)
            }
            // Let AppKit publish the native file-URL/filename representations and access grants.
            // Never publish a file's name/path as a text substitute. Validate ALL files first.
            pasteboard.clearContents()
            return pasteboard.writeObjects(files)
        }
        var items: [NSPasteboardItem] = []
        for representations in payload.items {
            let item = NSPasteboardItem()
            for representation in representations {
                guard item.setData(representation.data, forType: NSPasteboard.PasteboardType(representation.type)) else { return false }
            }
            items.append(item)
        }
        pasteboard.clearContents()
        return pasteboard.writeObjects(items)
    }

    public func clear() { pasteboard.clearContents() }
}

/// One timer per app; no event tap, global keyboard listener or background launch agent.
@MainActor public final class ClipboardMonitor {
    private var timer: Timer?
    public init() {}
    public var isRunning: Bool { timer != nil }
    public func start(poll: @escaping @MainActor () -> Void) {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }
    public func stop() { timer?.invalidate(); timer = nil }
    deinit { timer?.invalidate() }
}
